export type CountryCode = (typeof COUNTRY_CODES)[number];

/** The country the product is built for: the default when nothing else is known. */
export const HOME_COUNTRY: CountryCode = "NL";

const CODE_SET: ReadonlySet<string> = new Set(COUNTRY_CODES);

/** A code that is a real country, upper-cased; anything else is null. */
export function normalizeCountry(raw: unknown): CountryCode | null {
  if (typeof raw !== "string") return null;
  const code = raw.trim().toUpperCase();
  return CODE_SET.has(code) ? (code as CountryCode) : null;
}

/** The name of a country in the given language ("Verenigd Koninkrijk" / "United Kingdom"); the code itself if the runtime has no name. */
export function countryName(code: string, locale: "nl" | "en"): string {
  try {
    return new Intl.DisplayNames([locale], { type: "region" }).of(code) ?? code;
  } catch {
    return code;
  }
}

/** Every country as { code, name }, sorted by name in the language of the visitor. */
export function countryOptions(locale: "nl" | "en"): { code: CountryCode; name: string }[] {
  const collator = new Intl.Collator(locale === "nl" ? "nl" : "en");
  return COUNTRY_CODES.map((code) => ({ code, name: countryName(code, locale) })).sort((a, b) => collator.compare(a.name, b.name));
}
