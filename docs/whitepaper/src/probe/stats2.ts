import { ALL_ACTIVITIES, TAGS, DOMAINS, SUB_DOMAINS as SUBS, HYBRIDS } from "@/lib/discovery/library";
import { buildGraph, BRIDGE_MIN } from "@/lib/discovery/engine/graph";
import { registerOfActivity } from "@/lib/discovery/register";
import { ASSOCIATIONS } from "@/lib/discovery/associations";
import { registerOfCard } from "@/lib/discovery/register";
import { getActivities } from "@/lib/discovery/library";
import ca from "@/lib/discovery/cardAssociations.json";
import aa from "@/lib/discovery/activityAssociations.json";
import { clusterOf, MAX_PER_CLUSTER } from "@/lib/discovery/clusters";
const acts = getActivities();
const out: any = { visible: acts.length, all: ALL_ACTIVITIES.length };
out.domains = DOMAINS.map((d: any) => ({ id: d.id, nl: d.short.nl, n: acts.filter((a) => a.domain === d.id).length, subs: SUBS.filter((s: any) => s.domain === d.id).map((s: any) => `${s.label.nl}(${acts.filter((a) => a.sub === s.id).length})`) }));
const uses = new Map<string, number>(); for (const a of acts) for (const t of a.tags) uses.set(t, (uses.get(t) ?? 0) + 1);
out.tags = TAGS.map((t: any) => ({ id: t.id, nl: t.label.nl, generic: t.generic, n: uses.get(t.id) ?? 0 })).sort((a: any, b: any) => b.n - a.n);
out.avgTags = +(acts.reduce((s, a) => s + a.tags.length, 0) / acts.length).toFixed(2);
const g = buildGraph(acts, TAGS as any);
let edges = 0; const deg = new Map<string, number>();
for (let i = 0; i < acts.length; i++) for (let j = i + 1; j < acts.length; j++) if (g.bridge(acts[i], acts[j]) >= BRIDGE_MIN) { edges++; deg.set(acts[i].id, (deg.get(acts[i].id) ?? 0) + 1); deg.set(acts[j].id, (deg.get(acts[j].id) ?? 0) + 1); }
out.edges = edges; out.avgDeg = +(2 * edges / acts.length).toFixed(1);
out.isolated = acts.filter((a) => !deg.has(a.id)).length;
out.topHubs = [...deg].sort((a, b) => b[1] - a[1]).slice(0, 8).map(([id, d]) => `${acts.find((a) => a.id === id)!.label.nl}(${d})`);
out.rarest = [...acts].sort((a, b) => g.rarity(b) - g.rarity(a)).slice(0, 5).map((a) => a.label.nl);
const reg: Record<string, number> = {}; for (const a of acts) { const r = registerOfActivity(a); reg[r] = (reg[r] ?? 0) + 1; } out.activityRegisters = reg;
const creg: Record<string, number> = {}; for (const c of ASSOCIATIONS as any[]) { const r = registerOfCard(c); creg[r] = (creg[r] ?? 0) + 1; } out.cardRegisters = creg;
out.cardAssocFamilies = Object.keys(ca as any).length; out.activitiesWithVector = Object.keys((aa as any).activities).length; out.assocIdf = Object.keys((aa as any).idf).length;
out.hybrids = HYBRIDS.length;
out.clusters = acts.filter((a) => clusterOf(a.id)).length; out.maxPerCluster = MAX_PER_CLUSTER;
const imagePending = ALL_ACTIVITIES.filter((a: any) => a.image_pending).length; out.imagePending = imagePending;
const sample = acts.filter((a) => a.safety.tier === 2).length; out.tier2 = sample;
out.provenance = { source: acts.filter((a: any) => a.provenance?.method === "source").length, inferred: acts.filter((a: any) => a.provenance?.method === "inferred_ai").length, reviewed: acts.filter((a: any) => a.reviewed_by).length };
console.log(JSON.stringify(out, null, 1));
